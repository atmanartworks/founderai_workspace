CREATE OR REPLACE FUNCTION "public"."search_embeddings"("query_embedding" "public"."vector", "user_id" "uuid", "match_count" integer DEFAULT 5) RETURNS TABLE("id" "uuid", "vault_id" "uuid", "content" "text", "chunk_index" integer, "similarity" double precision)
    LANGUAGE "sql" STABLE
    AS $$
  select
    dc.id,
    dc.vault_id,
    dc.content,
    dc.chunk_index,
    1 - (dc.embedding <=> query_embedding) as similarity
  from document_chunks dc
  join vault_files vf on vf.id = dc.vault_id
  where vf.user_id = search_embeddings.user_id
  order by dc.embedding <=> query_embedding
  limit search_embeddings.match_count;
$$;


